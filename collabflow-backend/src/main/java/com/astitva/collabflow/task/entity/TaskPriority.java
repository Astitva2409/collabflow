package com.astitva.collabflow.task.entity;

/**
 * Represents priority level of a task.
 */
public enum TaskPriority {

    /**
     * Low priority task.
     */
    LOW,

    /**
     * Default priority.
     */
    MEDIUM,

    /**
     * High priority task.
     */
    HIGH,

    /**
     * Urgent task requiring immediate attention.
     */
    URGENT
}